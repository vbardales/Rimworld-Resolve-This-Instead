// Generates FRENCH_REVIEW.md at the mod root from the shipped XML (TRANSLATIONS.md, "Review file").
// Run from the repository root: node Tests/Make-FrenchReview.js <revision>
const fs = require("fs");
const rev = process.argv[2] || "unknown";

function pairs(path) {
  const s = fs.readFileSync(path, "utf8").replace(/<\/?LanguageData>/g, "");
  const out = [];
  const re = /<([A-Za-z0-9_.\-]+)>([\s\S]*?)<\/\1>/g;
  let m;
  while ((m = re.exec(s))) out.push([m[1], m[2].replace(/\r?\n/g, "\\n")]);
  return out;
}
const esc = (t) => t.replace(/\|/g, "\\|");

let md = `# French review file — Resolve This Instead\n\n` +
  `Generated by \`Tests/Make-FrenchReview.js\` from the shipped XML, revision ${rev}. This mod has no source text in another language: ` +
  `the Original column repeats the English. No text agrees with a pawn, so no gender switch is needed. Not reviewed yet.\n\n`;

const sections = [
  ["Keyed", "Mod/Languages/%L/Keyed/RTI.xml", null],
  ["DefInjected / MainButtonDef", "Mod/Languages/%L/DefInjected/MainButtonDef/RTI.xml", "Mod/Defs/MainButtonDefs.xml"],
];
for (const [title, template, defFile] of sections) {
  const french = pairs(template.replace("%L", "French"));
  let english = {};
  if (defFile) {
    // English comes from the Def itself (game's native fallback): <label> and <description>.
    const def = fs.readFileSync(defFile, "utf8");
    for (const f of ["label", "description"]) {
      const m = def.match(new RegExp(`<${f}>([\\s\\S]*?)</${f}>`));
      if (m) english[`RTI_Settings.${f}`] = m[1];
    }
  } else {
    english = Object.fromEntries(pairs(template.replace("%L", "English")));
  }
  md += `## ${title}\n\n| Key or path | Original | English | French |\n|---|---|---|---|\n`;
  for (const [key, fr] of french) {
    const en = english[key] ?? "(missing)";
    md += `| ${key} | ${esc(en)} | ${esc(en)} | ${esc(fr)} |\n`;
  }
  md += "\n";
}
fs.writeFileSync("FRENCH_REVIEW.md", md);
